#!/usr/bin/env node
// Vendors the Sektar design system into editors/sektar/design/ so the app
// ships a plain copy with no hand edits downstream of this script.
//
//   node scripts/sync-design-system.mjs [path/to/design-system]
//
// What it does:
//   - copies tokens/base/components/utilities.css (base.css is kept as the
//     reference for app.css's scoped typography; it is not imported — its
//     global reset would fight Connect's own chrome)
//   - rewrites `../assets/…` urls in the CSS to the vendored paths and checks
//     every referenced file was vendored
//   - copies the icon and brand-mark sprites, the favicon, the app icons and
//     the logos and shapes the app references (never the stucco variants or the photos)
//   - regenerates icons.ts / marks.ts: the sprites as TS string modules,
//     because `ph build` (tsdown) cannot load `?raw` imports
//   - prunes vendored logos/shapes that are no longer in the manifest
//   - writes SNAPSHOT.md with the source files, their mtimes and sha1
//
// Theme: the design system selects dark mode with `data-theme="dark"` on the
// root; Connect writes `.dark`. The app mirrors Connect's theme onto the
// attribute (kit/theme.ts), so tokens.css is vendored unmodified.
//
// Fonts: Fraunces stays on Google Fonts (index.html); the self-hosted TTFs
// (css/fonts.css, assets/fonts/) are deliberately not vendored.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const src = path.resolve(
  process.argv[2] ??
    process.env.SEKTAR_DESIGN_SYSTEM ??
    path.join(root, "..", "sektar-design-elements", "design-system"),
);
const out = path.join(root, "editors", "sektar", "design");

if (!fs.existsSync(path.join(src, "css", "components.css"))) {
  console.error(`design system not found at ${src}`);
  process.exit(1);
}

const CSS = ["tokens.css", "base.css", "components.css", "utilities.css"];

/** source path (relative to the design system) → vendored path (relative to out) */
const ASSETS = {
  "assets/icons.svg": "icons.svg",
  "assets/marks.svg": "marks.svg",
  "assets/favicon.svg": "favicon.svg",
};
for (const kind of ["horizontal", "symbol", "wordmark"]) {
  for (const tone of ["light", "dark"]) {
    const name =
      kind === "horizontal"
        ? `sektar-logo-horizontal-${tone}.svg`
        : `sektar-${kind}-${tone}.svg`;
    ASSETS[`assets/logos/${name}`] = `logos/${name}`;
  }
}
// App icons for the product switcher (one fill per product, light/dark)
for (const fill of ["forest", "sage"]) {
  for (const tone of ["light", "dark"]) {
    ASSETS[`assets/app-icons/sektar-app-icon-${fill}-${tone}.svg`] =
      `app-icons/sektar-app-icon-${fill}-${tone}.svg`;
  }
}
for (const shape of [
  "sektar-pattern-repeat",
  "sektar-growth-four-column-combined",
  "sektar-growth-double-curved",
  "sektar-composition-rise",
  "sektar-composition-quarter",
]) {
  for (const tone of ["light", "dark"]) {
    ASSETS[`assets/shapes/${shape}-${tone}.svg`] = `shapes/${shape}-${tone}.svg`;
  }
}

const sha1 = (buf) => createHash("sha1").update(buf).digest("hex").slice(0, 12);
const snapshot = [];
const vendored = new Set();

function record(rel, buf) {
  const st = fs.statSync(path.join(src, rel));
  snapshot.push({ rel, mtime: st.mtime.toISOString(), sha1: sha1(buf) });
}

function write(relOut, content) {
  const p = path.join(out, relOut);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, content);
  vendored.add(relOut.replaceAll("\\", "/"));
}

// 1. CSS, with asset urls rewritten to the vendored layout
const missing = new Set();
for (const file of CSS) {
  const rel = `css/${file}`;
  const raw = fs.readFileSync(path.join(src, rel), "utf8");
  record(rel, raw);
  const rewritten = raw.replace(
    /url\((["']?)\.\.\/assets\/([^"')]+)\1\)/g,
    (_m, q, asset) => {
      const target = ASSETS[`assets/${asset}`];
      if (!target) missing.add(asset);
      return `url(${q}./${target ?? asset}${q})`;
    },
  );
  write(file, rewritten);
}

// 2. Assets
for (const [rel, relOut] of Object.entries(ASSETS)) {
  const buf = fs.readFileSync(path.join(src, rel));
  record(rel, buf);
  write(relOut, buf);
}

// 3. Sprites as string modules
function stringModule(name, relOut, note) {
  const svg = fs.readFileSync(path.join(out, relOut), "utf8");
  const escaped = svg.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return `// ${note}\n// Source: ${relOut} next to this file (design-system/assets/${relOut}).\n// Generated by scripts/sync-design-system.mjs — do not edit.\nexport const ${name} = \`${escaped}\`;\n`;
}
write(
  "icons.ts",
  stringModule(
    "sprite",
    "icons.svg",
    "The Sektar icon sprite as a string, so it bundles without a `?raw` loader.",
  ),
);
write(
  "marks.ts",
  stringModule(
    "marks",
    "marks.svg",
    "The Sektar brand marks (symbol + wordmark) as a string, for the live lockup.",
  ),
);

// 4. Prune stale logos/shapes
for (const dir of ["logos", "shapes", "app-icons"]) {
  const d = path.join(out, dir);
  if (!fs.existsSync(d)) continue;
  for (const f of fs.readdirSync(d)) {
    const rel = `${dir}/${f}`;
    if (!vendored.has(rel)) {
      fs.rmSync(path.join(d, f));
      console.log(`pruned  ${rel}`);
    }
  }
}

// 5. Snapshot
snapshot.sort((a, b) => a.rel.localeCompare(b.rel));
const lines = [
  "# Vendored design system",
  "",
  `Source: \`${path.relative(root, src).replaceAll("\\", "/")}\``,
  `Synced: ${new Date().toISOString()} by \`scripts/sync-design-system.mjs\``,
  "",
  "Not vendored on purpose: `css/fonts.css` and `assets/fonts/` (Fraunces stays on Google Fonts), `css/docs.css`, `js/`, photos, stucco shape variants.",
  "`base.css` is vendored for reference only; `app.css` carries its typography scoped to `.sk-page` / `.sk-app`.",
  "",
  "| Source | Modified | sha1 |",
  "|---|---|---|",
  ...snapshot.map((s) => `| ${s.rel} | ${s.mtime} | ${s.sha1} |`),
  "",
];
write("SNAPSHOT.md", lines.join("\n"));

console.log(`synced ${CSS.length} stylesheets and ${Object.keys(ASSETS).length} assets from ${src}`);
if (missing.size) {
  console.warn(
    `WARNING: the CSS references assets that are not in the manifest: ${[...missing].join(", ")}`,
  );
  process.exitCode = 2;
}
