import type { Reducer, StateReducer } from "document-model";
import { createReducer, isDocumentAction } from "document-model";
import type { CalendarEventPHState } from "document-models/calendar-event/v1";

import { calendarEventCaptureOperations } from "../src/reducers/capture.js";

import { CaptureEventInputSchema } from "./schema/zod.js";

const schemaMemo = new Map<() => unknown, unknown>();

function memoizedSchema<T>(makeSchema: () => T): T {
  let schema = schemaMemo.get(makeSchema) as T | undefined;
  if (schema === undefined) {
    schema = makeSchema();
    schemaMemo.set(makeSchema, schema);
  }
  return schema;
}

const stateReducer: StateReducer<CalendarEventPHState> = (
  state,
  action,
  dispatch,
) => {
  if (isDocumentAction(action)) {
    return state;
  }
  switch (action.type) {
    case "CAPTURE_EVENT": {
      memoizedSchema(CaptureEventInputSchema).parse(action.input);

      calendarEventCaptureOperations.captureEventOperation(
        (state as any)[action.scope],
        action as any,
        dispatch,
      );

      break;
    }

    default:
      return state;
  }
};

export const reducer: Reducer<CalendarEventPHState> =
  createReducer(stateReducer);
